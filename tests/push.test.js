const test = require('node:test');
const assert = require('node:assert/strict');
const webpush = require('web-push');
const crypto = require('node:crypto');
const { startMockDatabase, fixture } = require('./mock-database');
const { deliverNotifications } = require('../lib/push');
test('fila: aguarda aparelho, usa recibos, tenta novamente e remove endpoints expirados', { timeout: 15000 }, async t => {
  const mock = await startMockDatabase();
  t.after(() => mock.close());
  process.env.SUPABASE_URL = mock.url;
  process.env.SUPABASE_SERVICE_ROLE_KEY = 'test-service-key';
  const keys = webpush.generateVAPIDKeys();
  process.env.VAPID_PUBLIC_KEY = keys.publicKey; process.env.VAPID_PRIVATE_KEY = keys.privateKey; process.env.VAPID_SUBJECT = 'https://example.com';
  const original = webpush.sendNotification;
  t.after(() => { webpush.sendNotification = original; });
  const ecdh = crypto.createECDH('prime256v1'); ecdh.generateKeys();
  const sub = suffix => ({ endpoint: 'https://web.push.apple.com/test-only-' + suffix, keys: { p256dh: ecdh.getPublicKey().toString('base64url'), auth: crypto.randomBytes(16).toString('base64url') } });
  const first = fixture(); mock.state.leads.push(first);
  assert.deepEqual(await deliverNotifications(first.id), { sent: 0, waitingForDevice: true });
  assert.equal(first.notification_sent_at, null);
  const a = sub('a'), b = sub('b'); mock.state.subscriptions.push(a, b);
  mock.state.receipts.push({ lead_id: first.id, endpoint: a.endpoint });
  const calls = [];
  webpush.sendNotification = async (device, payload) => { calls.push({ device, payload: JSON.parse(payload) }); return { statusCode: 201 }; };
  assert.equal((await deliverNotifications(first.id)).sent, 1);
  assert.equal(calls.length, 1, 'device with an existing receipt must not be sent again');
  assert.equal(calls[0].device.endpoint, b.endpoint);
  assert.equal(calls[0].payload.lead_id, first.id);
  assert.equal(JSON.stringify(calls[0].payload).includes(first.whatsapp), false);
  assert.equal(JSON.stringify(calls[0].payload).includes(first.nome), false);
  assert.ok(first.notification_sent_at);
  assert.equal((await deliverNotifications()).attempted, 0);
  const retry = fixture(); mock.state.leads.push(retry);
  webpush.sendNotification = async () => { throw Object.assign(Error('temporary failure'), { statusCode: 503 }); };
  assert.equal((await deliverNotifications(retry.id)).sent, 0);
  assert.equal(retry.notification_sent_at, null); assert.equal(retry.notification_error, 'PUSH_DELIVERY_FAILED');
  assert.ok(Date.parse(retry.notification_next_at) > Date.now());
  assert.equal((await deliverNotifications(retry.id)).attempted, 0);
  retry.notification_next_at = new Date(Date.now() - 1000).toISOString();
  webpush.sendNotification = async () => ({ statusCode: 201 });
  assert.equal((await deliverNotifications(retry.id)).sent, 1); assert.ok(retry.notification_sent_at);
  const expired = fixture(); mock.state.leads.push(expired);
  webpush.sendNotification = async () => { throw Object.assign(Error('expired'), { statusCode: 410 }); };
  assert.equal((await deliverNotifications(expired.id)).sent, 0);
  assert.equal(mock.state.subscriptions.length, 0);
  assert.equal(expired.notification_sent_at, null); assert.equal(expired.notification_error, 'NO_ACTIVE_PUSH_DEVICES');
});
