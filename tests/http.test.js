const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const webpush = require('web-push');
const { startMockDatabase, fixture } = require('./mock-database');
test('HTTP: autenticação, gravação, idempotência, filtros, paginação e logout', { timeout: 60000 }, async t => {
  const mock = await startMockDatabase();
  const origin = 'http://127.0.0.1:3033';
  const keys = webpush.generateVAPIDKeys();
  const app = spawn(process.execPath, ['scripts/dev.js'], { env: { ...process.env, PORT: '3033', ALM_PUBLIC_ORIGIN: origin, SUPABASE_URL: mock.url, SUPABASE_SERVICE_ROLE_KEY: 'test-service-key', ADMIN_PASSWORD: 'test-password-only', ADMIN_SESSION_SECRET: 'local-test-session-secret'.repeat(3), VAPID_PUBLIC_KEY: keys.publicKey, VAPID_PRIVATE_KEY: keys.privateKey, VAPID_SUBJECT: 'https://example.com', CRON_SECRET: 'test-cron-secret', ALM_TEST_MODE: '1' }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
  t.after(async () => { app.kill(); await mock.close(); });
  let output = '';
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(Error('App startup timed out: ' + output)), 15000);
    app.stdout.on('data', chunk => { output += chunk; if (output.includes('Local:')) { clearTimeout(timer); resolve(); } });
    app.stderr.on('data', chunk => { output += chunk; });
    app.on('exit', code => { if (code) { clearTimeout(timer); reject(Error('App failed: ' + output)); } });
  });
  let cookie = '';
  const request = async (path, options = {}) => {
    const response = await fetch(origin + path, { method: options.method || 'GET', headers: { Origin: options.origin || origin, ...(cookie ? { Cookie: cookie } : {}), ...(options.body ? { 'Content-Type': 'application/json' } : {}) }, body: options.body ? JSON.stringify(options.body) : undefined });
    const data = await response.json().catch(() => null); return { response, data };
  };
  const requestsBefore = mock.state.requests;
  assert.equal((await request('/api/admin/leads')).response.status, 401);
  assert.equal(mock.state.requests, requestsBefore, 'unauthenticated request must not read data');
  assert.equal((await request('/api/admin/session', { method: 'POST', origin: 'https://evil.example', body: { password: 'test-password-only' } })).response.status, 403);
  assert.equal((await request('/api/admin/session', { method: 'POST', body: { password: 'wrong' } })).response.status, 401);
  const login = await request('/api/admin/session', { method: 'POST', body: { password: 'test-password-only' } });
  assert.equal(login.response.status, 200); cookie = login.response.headers.get('set-cookie').split(';')[0];
  assert.match(login.response.headers.get('set-cookie'), /HttpOnly; SameSite=Strict/);
  assert.equal((await request('/api/admin/session')).data.authenticated, true);
  const lead = { submission_id: crypto.randomUUID(), nome: 'Teste Técnico', empresa: 'Empresa Teste', whats: '11900000000', ig: '@teste', answers: { atende: 'Um time comercial', espera: 'Algumas horas', leads: 'De 500 a 2.000', perdas: ['Follow-up que ninguém faz'], segmento: 'Serviços e consultoria', investimento: 'Sim, se resolver, faz sentido' }, utm: { utm_source: 'integration-test', utm_campaign: 'test' } };
  const first = await request('/api/leads', { method: 'POST', body: lead });
  assert.equal(first.response.status, 200); assert.equal(first.data.tier, 'alto'); assert.equal(mock.state.leads.length, 1);
  assert.equal((await request('/api/leads', { method: 'POST', body: lead })).data.id, first.data.id);
  assert.equal(mock.state.leads.length, 1, 'retry must not create a second record');
  let panel = await request('/api/admin/leads');
  assert.equal(panel.response.status, 200); assert.equal(panel.data.leads[0].respostas.espera, 'Algumas horas');
  assert.equal(panel.data.leads[0].utm.utm_source, 'integration-test');
  assert.match(panel.response.headers.get('cache-control'), /no-store/);
  assert.equal((await request('/api/admin/leads', { method: 'POST', body: { action: 'read', id: first.data.id } })).response.status, 200);
  assert.equal((await request('/api/admin/leads?unread=1')).data.leads.length, 0);
  assert.equal((await request('/api/admin/leads?q=Empresa')).data.leads.length, 1);
  assert.equal((await request('/api/admin/leads?tier=baixo')).data.leads.length, 0);
  assert.equal((await request('/api/admin/push', { method: 'POST', body: { action: 'subscribe', subscription: { endpoint: 'https://127.0.0.1/private', keys: {} } } })).response.status, 400);
  assert.equal((await request('/api/cron/deliveries')).response.status, 401);
  for (let i = 0; i < 55; i++) mock.state.leads.push(fixture({ created_at: new Date(Date.now() - (i + 1) * 60000).toISOString() }));
  panel = await request('/api/admin/leads'); assert.equal(panel.data.leads.length, 50); assert.ok(panel.data.nextCursor);
  const next = await request('/api/admin/leads?cursor=' + encodeURIComponent(panel.data.nextCursor));
  assert.equal(next.data.leads.length, 6); assert.equal(next.data.nextCursor, null);
  assert.equal(next.data.leads.some(l => panel.data.leads.some(p => p.id === l.id)), false);
  assert.equal((await request('/api/admin/leads?cursor=bad')).response.status, 400);
  assert.equal((await request('/api/admin/session', { method: 'DELETE' })).response.status, 200);
  cookie = ''; assert.equal((await request('/api/admin/leads')).response.status, 401);
  for (const path of ['/.env.local', '/lib/admin.js', '/scripts/setup.js', '/supabase/001_alm_ai.sql']) assert.equal((await fetch(origin + path)).status, 404);
});
